// 节日 → 日期（parse.ts 用）。
//
// 公历节日按月日固定，年年一样；春节 / 清明 / 端午 / 中秋 跟着农历（清明其实是节气）走，
// 每年都漂，这里没有农历算法，**查表**：2025–2030 六年。
// 表外的年份一律不认——解析器会把原文留在标题里，绝不硬猜一个日子出来。
// 口径跟「N月N日」一样：今年那次还没过就取今年，过了取明年；明年也不在表里就不认。

/** 公历固定节日：规范名 → 'MM-DD' */
const FIXED: Record<string, string> = {
  元旦: "01-01",
  情人节: "02-14",
  劳动节: "05-01",
  儿童节: "06-01",
  国庆节: "10-01",
  圣诞节: "12-25",
};

/** 农历节日（含清明）按年查表：年份 → 规范名 → 'MM-DD'。
 *  每一格都对过万年历，错一天就是产品事故，改之前先核 */
const LUNAR: Record<number, Record<string, string>> = {
  2025: { 春节: "01-29", 清明: "04-04", 端午: "05-31", 中秋: "10-06" },
  2026: { 春节: "02-17", 清明: "04-05", 端午: "06-19", 中秋: "09-25" },
  2027: { 春节: "02-06", 清明: "04-05", 端午: "06-09", 中秋: "09-15" },
  2028: { 春节: "01-26", 清明: "04-04", 端午: "05-28", 中秋: "10-03" },
  2029: { 春节: "02-13", 清明: "04-04", 端午: "06-16", 中秋: "09-22" },
  2030: { 春节: "02-03", 清明: "04-05", 端午: "06-05", 中秋: "09-12" },
};

/** 各种叫法 → 规范名。解析器的正则按这张表的键生成（长词在前） */
const ALIAS: Record<string, string> = {
  五一劳动节: "劳动节",
  劳动节: "劳动节",
  五一节: "劳动节",
  五一: "劳动节",
  六一儿童节: "儿童节",
  儿童节: "儿童节",
  六一: "儿童节",
  国庆节: "国庆节",
  国庆: "国庆节",
  元旦节: "元旦",
  元旦: "元旦",
  情人节: "情人节",
  圣诞节: "圣诞节",
  圣诞: "圣诞节",
  春节: "春节",
  清明节: "清明",
  清明: "清明",
  端午节: "端午",
  端午: "端午",
  中秋节: "中秋",
  中秋: "中秋",
};

/** 解析器认得的所有节日写法，长的在前（「劳动节」得先于「五一」试，否则「五一劳动节」会被拆成两截） */
export const HOLIDAY_WORDS: string[] = Object.keys(ALIAS).sort((a, b) => b.length - a.length);

/** 某个节日写法 → 'YYYY-MM-DD'。today 是 'YYYY-MM-DD'。
 *  不带 which：今年那次 >= today 取今年，否则取明年；农历节日明年不在表里就返回 null（不认）。
 *  which = "明年"：一律取明年那次（哪怕今年的还没过）；"今年"：一律取今年那次（哪怕已经过了）。
 *  指定的那一年不在表里同样返回 null */
export function holidayDate(word: string, today: string, which?: "今年" | "明年"): string | null {
  const name = ALIAS[word];
  if (name === undefined) return null;
  const y = Number(today.slice(0, 4));
  const years = which === "今年" ? [y] : which === "明年" ? [y + 1] : [y, y + 1];
  for (const year of years) {
    const md = FIXED[name] ?? LUNAR[year]?.[name];
    if (md === undefined) continue;
    const cand = `${year}-${md}`;
    if (which !== undefined || cand >= today) return cand;
  }
  return null;
}
